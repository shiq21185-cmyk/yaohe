#ifndef __BSP_TIME_H
#define __BSP_TIME_H

#include <stdint.h>

/* ==========================================================================
 * 时基层
 * --------------------------------------------------------------------------
 * 把"TIM4 被配成 1 MHz 自由运行计数器"这个硬件细节收敛在 BSP 里，
 * 上层只用微秒/毫秒/秒这类语义化延时，不再直接操作 TIM 寄存器。
 * ========================================================================== */

/* 配置 TIM4 为 1 MHz 向上计数；上电调用一次即可。 */
void BSP_Time_Init(void);

/* 忙等延时（不进入调度器，可在中断上下文使用）。 */
void BSP_DelayUs(uint32_t us);      /* 单次范围 0 ~ 65535us，超出按上限截断 */
void BSP_DelayMs(uint32_t ms);
void BSP_DelayS(uint32_t s);

/* 读取 1 MHz 计数器当前值，供上层做短超时轮询。 */
uint16_t BSP_Time_GetCounter(void);

#endif
